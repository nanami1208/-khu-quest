/* ---------- 保存（localStorage。使えない環境でもゲームは動く） ---------- */
window.KHUStore = (function () {
  const KEY = 'khuquest.save.v1';
  const blank = () => ({ notes: {}, plays: 0, clears: 0, bestScore: null, quizMax: 0, muted: false });
  let mem = blank();
  function load() {
    try {
      const raw = localStorage.getItem(KEY);
      if (raw) mem = Object.assign(blank(), JSON.parse(raw));
    } catch (e) { /* プライベートモード等 */ }
    return mem;
  }
  function save() {
    try { localStorage.setItem(KEY, JSON.stringify(mem)); } catch (e) {}
  }
  load();
  return {
    get data() { return mem; },
    load, save,
    has(id) { return !!mem.notes[id]; },
    /* 新しく手に入れたら true を返す */
    unlock(id) {
      if (mem.notes[id]) return false;
      mem.notes[id] = Date.now();
      save();
      return true;
    },
    count() { return Object.keys(mem.notes).filter(id => window.KHU_NOTES.some(n => n.id === id)).length; },
    reset() { const m = mem.muted; mem = blank(); mem.muted = m; save(); },
  };
})();
